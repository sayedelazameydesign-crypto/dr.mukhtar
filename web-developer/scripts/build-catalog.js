#!/usr/bin/env node
/**
 * Generate (or verify) FEATURES.md from the single feature registry.
 *
 *   node web-developer/scripts/build-catalog.js          # write the catalog
 *   node web-developer/scripts/build-catalog.js --check  # fail on drift
 *
 * The catalog is documentation, not a second source of truth: every row comes from
 * engine/features.js, including the upstream to-do anchor.
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const W = require('../engine/features.js');

const ROOT = path.resolve(__dirname, '..');
const TARGET = path.join(ROOT, 'FEATURES.md');
const GROUPS = [
  ['feature', 'Requested features (Common)', 'New features from the Web Developer to-do list, implemented as real toggles or actions.'],
  ['enhancement', 'Requested enhancements', 'Upgrades to existing Web Developer features. The linked base feature carries the implementation.'],
  ['platform', 'Platform and Chrome items', 'Dashboard-level capabilities and Chrome-specific status/cookie support.'],
  ['base', 'Base features', 'Rebuilt so the requested enhancements have something real to enhance.']
];

const BASE_FOR = {
  'display-element-information-color': 'display-element-information',
  'display-line-guides-save': 'display-line-guides',
  'edit-css-color-picker': 'edit-css',
  'edit-css-mime-warning': 'edit-css',
  'outline-images-adjusted-dimensions': 'outline-images-with-adjusted-dimensions',
  'populate-form-fields-configurable': 'populate-form-fields',
  'validators-configurable': 'validate-local-html / validate-local-css',
  'view-cookie-information-csv': 'view-cookie-information',
  'view-image-information-grid': 'view-image-information',
  'view-link-information-details': 'view-link-information',
  'view-link-information-split': 'view-link-information',
  'display-element-information-position': 'display-element-information',
  'view-color-information-gradients': 'view-color-information',
  'sort-color-information': 'view-color-information',
  'split-id-class-details': 'display-id-details / display-class-details',
  'same-site-cookies': 'view-cookie-information'
};

function row(feature) {
  const label = feature.url ? `[${feature.label}](${feature.url})` : feature.label;
  const location = feature.mode === 'ui'
    ? `dashboard.js · \`${feature.ui}\``
    : `engine/features.js · \`${feature.id}\``;
  const link = BASE_FOR[feature.id] ? ` — via \`${BASE_FOR[feature.id]}\`` : '';
  const chrome = feature.category === 'Chrome' ? ' (Chrome)' : '';
  return `| ${label}${chrome} | \`${feature.mode}\` | ${location}${link} | ${feature.description.replace(/\|/g, '\\|')} |`;
}

let out = `# Web Developer — feature catalog

> Generated by \`node web-developer/scripts/build-catalog.js\`. Do not edit by hand:
> the registry in \`engine/features.js\` is the single source of truth.
> Every upstream link points at the matching to-do item on chrispederick.com.

**${W.FEATURES.length} features**: ${GROUPS.map(([id, title]) => {
  const count = W.FEATURES.filter((f) => f.group === id).length;
  return `${count} ${title.toLowerCase()}`;
}).join(' · ')}.

Modes: \`toggle\` = a stateful switch that restores the page when disabled;
\`action\` = a one-shot report/editor; \`ui\` = a dashboard capability (Options,
Templates, Shortcuts, Tools, status chips) implemented in \`dashboard.js\` and
\`extension/service-worker.js\`.

`;

GROUPS.forEach(([id, title, blurb]) => {
  const items = W.FEATURES.filter((f) => f.group === id);
  out += `## ${title} (${items.length})\n\n${blurb}\n\n`;
  out += '| Feature | Mode | Implemented in | What it does |\n| --- | --- | --- | --- |\n';
  out += items.map(row).join('\n') + '\n\n';
});

out += `## Verification

\`node scripts/test-web-developer.js\` exercises the pure helpers and, with jsdom,
the whole session runtime (toggles, restoration, reports, validators and CSV
export). \`node web-developer/scripts/build-catalog.js --check\` fails if this file
drifts from the registry.

The page-inspection features act on \`demo.html\` in standalone mode and on the
active tab through \`extension/content.js\` when \`web-developer/\` is loaded as an
unpacked Chrome extension. No clinic booking code is touched by this tool.
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
  if (current !== out) {
    console.error('✗ web-developer/FEATURES.md is out of date — run node web-developer/scripts/build-catalog.js');
    process.exit(1);
  }
  console.log(`Catalog OK (${W.FEATURES.length} features)`);
} else {
  fs.writeFileSync(TARGET, out);
  console.log(`Wrote ${path.relative(process.cwd(), TARGET)} (${W.FEATURES.length} features)`);
}
