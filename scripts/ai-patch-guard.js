#!/usr/bin/env node
'use strict';

/**
 * Patch guard — the only thing standing between a language model and this repository.
 *
 * A proposed repair is untrusted text until it passes every rule below. The guard is
 * deliberately narrow: it knows which files a machine may touch, how big a patch may be,
 * and what a patch must look like. It does not decide whether a fix is *correct* — that is
 * what the test suite is for — it decides whether the fix is *admissible*.
 *
 *   node scripts/ai-patch-guard.js --patch <file> [--json <out>]
 *   node scripts/ai-patch-guard.js --self-test
 *
 * Rules (each one is a test case in --self-test):
 *   1. Unified diff only. No binary hunks, no git am metadata, no "apply this command".
 *   2. Every path is relative, inside the repository, and free of `..` / absolute / NUL.
 *   3. Writable areas only: scripts/ and docs/, and the site files app.js/app.css/index.html.
 *      Explicitly protected: workflows, the secrets manifest, the env template, clinic.json,
 *      the privacy pages, generated gas/, deployment scripts, Google profile config.
 *   4. A patch cannot create executable surface: new files must be .js/.md under
 *      scripts//docs/, never shell, never a manifest that a runner would execute.
 *   5. Size limits: ≤ 5 files, ≤ 200 changed lines, ≤ 64 KB.
 *   6. No secret-shaped content, and no deletion-only hunk (a "fix" that removes a check
 *      without replacing it is not a fix).
 *
 * Exit codes: 0 admitted, 1 rejected, 2 usage error. A rejection always lists every
 * violated rule, so a human reviewing the refusal sees the whole picture at once.
 */

const fs = require('node:fs');
const path = require('node:path');

const LIMITS = { files: 5, changedLines: 200, bytes: 64 * 1024 };

/** Writing here is allowed. Everything else is protected by default. */
const WRITABLE = [
  /^scripts\/[A-Za-z0-9._-]+\.js$/,
  /^docs\/[A-Za-z0-9._/-]+\.md$/,
  /^docs\/map\/[A-Za-z0-9._-]+\.json$/
];
const SINGLE_FILES = new Set(['app.js', 'app.css', 'index.html']);

/** Protected even inside a writable area: these carry policy, secrets, or generated output. */
const PROTECTED = [
  { re: /^\.github\//, why: 'a repair must never edit the workflow that judges it' },
  { re: /^docs\/secrets(-manifest)?[.\w]*\.json$/, why: 'the secrets manifest is an owner decision' },
  { re: /^docs\/secrets\.md$/, why: 'the secrets runbook is an owner decision' },
  { re: /^docs\/privacy|^privacy\.html$/, why: 'privacy wording is a legal/policy decision, not a code fix' },
  { re: /^config\/\.env|^\.env/, why: 'environment templates are not code' },
  { re: /^clinic\.json$/, why: 'clinic facts (name, phone, licence) are owner-supplied' },
  { re: /^gas\//, why: 'gas/ is generated by scripts/build-gas-package.py, never edited by hand' },
  { re: /^_site\//, why: 'build output' },
  { re: /^scripts\/(?:bootstrap-github|enable-pages|pre-commit)\.sh$/, why: 'owner bootstrap and commit hooks stay manual' },
  { re: /^scripts\/google\//, why: 'credential bridge: a repair may read it, never rewrite it' },
  { re: /^config\/google\.profile/, why: 'credential profile' },
  { re: /^package(-lock)?\.json$/, why: 'dependency surface is a human decision' },
  { re: /^scripts\/ai-(?:repair|patch-guard)\.js$/, why: 'the repair engine must not rewrite its own guard' },
  { re: /^scripts\/ci-error-scanner\.js$/, why: 'the detector must not rewrite what it detects' }
];

const SECRET_SHAPED = [
  /AIza[0-9A-Za-z_-]{35}/,
  /gh[pousr]_[A-Za-z0-9]{36,}/,
  /github_pat_[A-Za-z0-9_]{22,}/,
  /GOCSPX-[A-Za-z0-9_-]{20,}/,
  /-----BEGIN (?:RSA |EC |OPENSSH |PGP )?PRIVATE KEY-----/,
  /eyJ[A-Za-z0-9_-]{10,}\.eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}/
];

/** Parse the file headers of a unified diff. Malformed input yields no headers, which fails closed. */
function parsePatch(text) {
  const files = [];
  const lines = String(text || '').split('\n');
  let current = null;
  let sawHunk = false;
  let added = 0;
  let removed = 0;

  lines.forEach((line) => {
    if (/^diff --git /.test(line)) {
      if (current) files.push(current);
      const match = /^diff --git a\/(\S+) b\/(\S+)$/.exec(line);
      current = { from: match ? match[1] : null, to: match ? match[2] : null, added: 0, removed: 0, newFile: false, binary: false };
      sawHunk = false;
      return;
    }
    if (!current) return;
    if (/^new file mode /.test(line)) current.newFile = true;
    if (/^deleted file mode /.test(line)) current.deleted = true;
    if (/^GIT binary patch/.test(line)) current.binary = true;
    if (/^@@/.test(line)) { sawHunk = true; return; }
    if (sawHunk && /^\+/.test(line) && !/^\+\+\+/.test(line)) { current.added += 1; added += 1; }
    if (sawHunk && /^-/.test(line) && !/^---/.test(line)) { current.removed += 1; removed += 1; }
  });
  if (current) files.push(current);

  return { files: files, added: added, removed: removed, hadHunk: sawHunk || files.some((file) => file.added || file.removed) };
}

function isWritable(file) {
  if (SINGLE_FILES.has(file)) return true;
  return WRITABLE.some((pattern) => pattern.test(file));
}

/**
 * @param {string} patchText  the proposed unified diff
 * @returns {{ok:boolean, violations:{rule:string, detail:string}[], stats:object}}
 */
function checkPatch(patchText) {
  const violations = [];
  const add = (rule, detail) => violations.push({ rule: rule, detail: detail });
  const text = String(patchText || '');

  if (!text.trim()) {
    add('empty', 'the patch is empty');
    return { ok: false, violations: violations, stats: {} };
  }
  if (Buffer.byteLength(text, 'utf8') > LIMITS.bytes) add('size-bytes', `patch is ${Buffer.byteLength(text, 'utf8')} bytes, limit ${LIMITS.bytes}`);
  if (/^From [0-9a-f]{40} /m.test(text) || /^Subject: \[PATCH/.test(text)) add('format', 'this is an mbox/git-am bundle, not a plain diff');

  const parsed = parsePatch(text);
  if (!parsed.files.length) add('format', 'no `diff --git` header found — only a plain unified diff is accepted');
  if (!parsed.hadHunk) add('format', 'the patch contains no hunk (@@)');
  if (parsed.files.length > LIMITS.files) add('size-files', `${parsed.files.length} files changed, limit ${LIMITS.files}`);
  const changedLines = parsed.added + parsed.removed;
  if (changedLines > LIMITS.changedLines) add('size-lines', `${changedLines} changed lines, limit ${LIMITS.changedLines}`);

  SECRET_SHAPED.forEach((pattern) => {
    if (pattern.test(text)) add('secret', 'the patch contains something shaped like a credential');
  });
  // Adding execution surface is never a repair. Matched on the imported/constructed name,
  // not on a call shape, so `const { execSync } = require("node:child_process")` is caught too.
  if (/^\+.*(?:\beval\s*\(|\bnew\s+Function\b|node:child_process|\bchild_process\b|\bexecSync\b|\bspawnSync\b|\bexecFileSync\b)/m.test(text)) {
    add('execution', 'the patch adds a process/eval call — the repair engine never introduces code execution');
  }

  parsed.files.forEach((file) => {
    const name = file.to || file.from || '(unnamed)';
    if (file.from && file.to && file.from !== file.to) add('rename', `${file.from} → ${file.to}: renames are not accepted`);
    if (file.binary) add('binary', `${name}: binary hunks are not accepted`);
    if (/\\/.test(name)) add('path', `${name}: backslashes are not a valid path separator here`);
    if (name === '(unnamed)' || name.startsWith('/') || /^[A-Za-z]:/.test(name)) add('path', `${name}: the path must be repository-relative`);
    if (/(^|\/)\.\.(\/|$)/.test(name)) add('path', `${name}: path traversal is refused`);
    if (/\0/.test(name)) add('path', 'NUL byte in a path');

    PROTECTED.forEach((rule) => {
      if (rule.re.test(name)) add('protected', `${name}: ${rule.why}`);
    });
    if (!isWritable(name)) add('outside-writable-area', `${name}: only scripts/*.js, docs/**/*.md and the three site files may be written`);
    if (file.newFile && !/\.(?:js|md)$/.test(name)) add('new-file', `${name}: a repair may only create .js or .md files`);
    if (file.deleted) add('deletion', `${name}: deleting a file is never a repair`);
  });

  if (parsed.files.length && parsed.removed > 0) {
    const deletionOnly = parsed.files.every((file) => file.removed > 0 && file.added === 0);
    if (deletionOnly) add('deletion-only', 'every hunk only removes lines — a check was deleted without a replacement');
  }

  return {
    ok: violations.length === 0,
    violations: violations,
    stats: { files: parsed.files.length, added: parsed.added, removed: parsed.removed, bytes: Buffer.byteLength(text, 'utf8') }
  };
}

/* ---------------------------------------------------------------- self-test */

const GOOD_PATCH = [
  'diff --git a/scripts/live-llm-smoke.js b/scripts/live-llm-smoke.js',
  '--- a/scripts/live-llm-smoke.js',
  '+++ b/scripts/live-llm-smoke.js',
  '@@ -1,3 +1,3 @@',
  ' const a = 1;',
  '-const enabled = false;',
  '+const enabled = process.env.LLM_SMOKE_ENABLED === "true";',
  ' module.exports = { a };',
  ''
].join('\n');

function selfTest() {
  const cases = [
    { name: 'a small fix inside scripts/ is admitted', patch: GOOD_PATCH, expect: true },
    { name: 'an edit to a workflow is refused', patch: GOOD_PATCH.replace(/scripts\/live-llm-smoke\.js/g, '.github/workflows/ci.yml'), expect: false, rule: 'protected' },
    { name: 'an edit to the secrets manifest is refused', patch: GOOD_PATCH.replace(/scripts\/live-llm-smoke\.js/g, 'docs/secrets-manifest.json'), expect: false, rule: 'protected' },
    { name: 'an edit to clinic.json is refused', patch: GOOD_PATCH.replace(/scripts\/live-llm-smoke\.js/g, 'clinic.json'), expect: false, rule: 'protected' },
    { name: 'an edit to a privacy page is refused', patch: GOOD_PATCH.replace(/scripts\/live-llm-smoke\.js/g, 'privacy.html'), expect: false, rule: 'protected' },
    { name: 'an edit to generated gas/ is refused', patch: GOOD_PATCH.replace(/scripts\/live-llm-smoke\.js/g, 'gas/Code.gs'), expect: false, rule: 'protected' },
    { name: 'an edit to the guard itself is refused', patch: GOOD_PATCH.replace(/scripts\/live-llm-smoke\.js/g, 'scripts/ai-patch-guard.js'), expect: false, rule: 'protected' },
    { name: 'path traversal is refused', patch: GOOD_PATCH.replace(/scripts\/live-llm-smoke\.js/g, 'scripts/../../etc/passwd.js'), expect: false, rule: 'path' },
    { name: 'an absolute path is refused', patch: GOOD_PATCH.replace(/scripts\/live-llm-smoke\.js/g, '/etc/passwd.js'), expect: false, rule: 'path' },
    { name: 'a binary hunk is refused', patch: GOOD_PATCH.replace('@@', 'GIT binary patch\n@@'), expect: false, rule: 'binary' },
    { name: 'a credential inside the patch is refused', patch: GOOD_PATCH.replace('const a = 1;', 'const a = "AIza' + 'A'.repeat(35) + '";'), expect: false, rule: 'secret' },
    { name: 'deleting a check without replacing it is refused', patch: [
      'diff --git a/scripts/test-gate.js b/scripts/test-gate.js',
      '--- a/scripts/test-gate.js',
      '+++ b/scripts/test-gate.js',
      '@@ -1,2 +1,0 @@',
      '-if (!ok) process.exit(1);',
      '-module.exports = {};',
      ''
    ].join('\n'), expect: false, rule: 'deletion-only' },
    { name: 'creating a shell script is refused', patch: [
      'diff --git a/scripts/fix.sh b/scripts/fix.sh',
      'new file mode 100755',
      '--- /dev/null',
      '+++ b/scripts/fix.sh',
      '@@ -0,0 +1 @@',
      '+rm -rf /',
      ''
    ].join('\n'), expect: false, rule: 'outside-writable-area' },
    { name: 'adding a child_process call is refused', patch: GOOD_PATCH.replace('-const enabled = false;', '+const { execSync } = require("node:child_process");'), expect: false, rule: 'execution' },
    { name: 'an empty patch is refused', patch: '   ', expect: false, rule: 'empty' }
  ];

  let failed = 0;
  cases.forEach((testCase) => {
    const result = checkPatch(testCase.patch);
    const ruleOk = !testCase.rule || result.violations.some((violation) => violation.rule === testCase.rule);
    if (result.ok === testCase.expect && ruleOk) console.log(`✓ self-test: ${testCase.name}`);
    else {
      console.error(`✗ self-test: ${testCase.name} (ok=${result.ok}, rules=${result.violations.map((violation) => violation.rule).join(',') || 'none'})`);
      failed += 1;
    }
  });

  // Size limits are about the whole patch, so they need generated input.
  const big = ['diff --git a/scripts/a.js b/scripts/a.js', '--- a/scripts/a.js', '+++ b/scripts/a.js', '@@ -1 +1,300 @@']
    .concat(Array.from({ length: 300 }, (unused, index) => `+line ${index}`)).join('\n');
  const bigResult = checkPatch(big);
  if (!bigResult.ok && bigResult.violations.some((violation) => violation.rule === 'size-lines')) console.log('✓ self-test: a 300-line patch exceeds the changed-line limit');
  else { console.error('✗ self-test: a 300-line patch exceeds the changed-line limit'); failed += 1; }

  if (failed) {
    console.error(`\nPatch guard self-test FAILED (${failed} of ${cases.length + 1}).`);
    return 1;
  }
  console.log(`\nPatch guard self-test passed: ${cases.length + 1} cases (admissible fix admitted, every unsafe shape refused).`);
  return 0;
}

/* --------------------------------------------------------------------- CLI */

function main(argv) {
  if (argv.includes('--self-test')) return selfTest();
  const index = argv.indexOf('--patch');
  if (index < 0 || !argv[index + 1]) {
    console.error('Usage: node scripts/ai-patch-guard.js --patch <file> [--json <out>] | --self-test');
    return 2;
  }
  const file = argv[index + 1];
  if (!fs.existsSync(file)) {
    console.error(`No such patch file: ${file}`);
    return 2;
  }
  const result = checkPatch(fs.readFileSync(file, 'utf8'));
  const outIndex = argv.indexOf('--json');
  if (outIndex >= 0 && argv[outIndex + 1]) {
    fs.writeFileSync(argv[outIndex + 1], `${JSON.stringify(result, null, 2)}\n`);
  }
  if (result.ok) {
    console.log(`Patch admitted — ${result.stats.files} file(s), +${result.stats.added}/-${result.stats.removed}, ${result.stats.bytes} bytes.`);
    return 0;
  }
  console.error(`Patch REFUSED — ${result.violations.length} violation(s):`);
  result.violations.forEach((violation) => console.error(` · [${violation.rule}] ${violation.detail}`));
  return 1;
}

if (require.main === module) {
  process.exit(main(process.argv.slice(2)));
}

module.exports = { checkPatch, parsePatch, LIMITS, WRITABLE, PROTECTED };
