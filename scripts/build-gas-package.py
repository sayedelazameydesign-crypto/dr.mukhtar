#!/usr/bin/env python3
"""Build the Google Apps Script package from the standalone site.

Outputs (all generated, all disposable):
  gas/Code.gs          copy of the backend (Code.gs)
  gas/Llm.gs           copy of the provider adapter (Llm.gs)
  gas/Settings.gs      copy of the editable-settings module (Settings.gs)
  gas/WhatsApp.gs      copy of the WhatsApp adapter (WhatsApp.gs, off by default)
  gas/Index.html       index.html with CSS + JS inlined for HtmlService
  gas/Fonts.html       @font-face rules with base64 woff2 payloads
  gas/appsscript.json  manifest with Africa/Cairo + required scopes

The build works from the repository layout (`index.html` at the root) and also
from the legacy layout that keeps sources in `public/` with the script under
`scripts/`.
"""
from __future__ import annotations

import base64
import mimetypes
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
OUT = ROOT / "gas"


def first_existing(*paths: Path) -> Path | None:
    for path in paths:
        if path.exists():
            return path
    return None


def load_sources() -> tuple[Path, Path, Path, Path]:
    html = first_existing(ROOT / "index.html", ROOT / "public" / "index.html")
    if html is None:
        sys.exit("index.html not found at the repository root or in public/")
    base = html.parent
    css = first_existing(base / "app.css", ROOT / "app.css")
    js = first_existing(base / "app.js", ROOT / "app.js")
    if css is None or js is None:
        sys.exit("app.css and app.js are required next to index.html")
    fonts = first_existing(ROOT / "assets" / "fonts", base / "assets" / "fonts")
    if fonts is None:
        sys.exit("assets/fonts not found")
    return html, css, js, fonts


def build_fonts_sheet(css: str, fonts_dir: Path) -> tuple[str, str]:
    """Return (html_for_Fonts_file, css_with_inline_data_uris)."""
    seen: dict[str, str] = {}

    def to_data_uri(raw_ref: str) -> str:
        if raw_ref.startswith("data:") or not re.search(r"\.(woff2?|ttf|otf)(\?|$)", raw_ref):
            return raw_ref
        rel = raw_ref.split("?", 1)[0].replace("./", "").replace("../", "")
        if rel in seen:
            return seen[rel]
        candidate = first_existing(fonts_dir / Path(rel).name, ROOT / rel, ROOT / "public" / rel)
        if candidate is None:
            print(f"  ! missing font asset: {rel}")
            return raw_ref
        mime = mimetypes.guess_type(candidate.name)[0] or "font/woff2"
        payload = base64.b64encode(candidate.read_bytes()).decode("ascii")
        seen[rel] = f"data:{mime};base64,{payload}"
        return seen[rel]

    font_faces: list[str] = []
    plain_css_parts: list[str] = []

    def take_font_block(match: re.Match[str]) -> str:
        font_faces.append(match.group(0))
        return ""

    # Pull @font-face declarations out of the main stylesheet, then re-inline
    # their sources so both plain HTML and HtmlService bundles stay self-contained.
    remaining = re.sub(r"@font-face\s*\{[^}]*\}", take_font_block, css)

    plain_css_parts.append(re.sub(r"url\((['\"]?)([^'\")]+)\1\)", lambda m: f"url({to_data_uri(m.group(2))})", remaining))

    font_css = "\n".join(font_faces)
    font_css = re.sub(r"url\((['\"]?)([^'\")]+)\1\)", lambda m: f"url({to_data_uri(m.group(2))})", font_css)
    plain_css = "\n".join(plain_css_parts).strip()

    fonts_html = (
        "<style>\n/* Generated by scripts/build-gas-package.py — do not edit. */\n"
        f"{font_css}\n</style>"
    )
    return fonts_html, plain_css


# The single source of truth for what the bundle contains. `--list` prints this without
# touching the disk, so scripts/check-rehearsal.js can verify that the rehearsal document and
# the checklist name every file (and no file that is not built).
GENERATED_FILES = ("Index.html", "Fonts.html")
COPIED_FILES = ("Code.gs", "Llm.gs", "Settings.gs", "WhatsApp.gs", "appsscript.json")


def bundle_files() -> list[str]:
    """Files the build produces, in a stable order."""
    return list(GENERATED_FILES) + [name for name in COPIED_FILES if (ROOT / name).exists()]


def main() -> None:
    if "--list" in sys.argv[1:]:
        for name in bundle_files():
            print(name)
        return
    html_path, css_path, js_path, fonts_dir = load_sources()
    html = html_path.read_text(encoding="utf-8")
    css = css_path.read_text(encoding="utf-8")
    js = js_path.read_text(encoding="utf-8")

    OUT.mkdir(parents=True, exist_ok=True)

    fonts_html, inline_css = build_fonts_sheet(css, fonts_dir)
    (OUT / "Fonts.html").write_text(fonts_html, encoding="utf-8")

    html, css_count = re.subn(
        r'[ \t]*<link rel="stylesheet" href="\./app\.css[^"]*">',
        lambda _m: "  <?!= include('Fonts'); ?>\n  <style>\n" + inline_css + "\n  </style>",
        html,
        count=1,
    )
    # HtmlService cannot defer an inline script, so drop the head tag now and
    # re-insert the same code just before </body> once the DOM exists.
    html, js_count = re.subn(r'[ \t]*<script src="\./app\.js[^"]*" defer></script>\n?', "", html, count=1)
    if css_count != 1 or js_count != 1:
        sys.exit("Could not find exactly one CSS and JS entry point in index.html")
    if "</body>" not in html:
        sys.exit("index.html is missing a closing </body> tag")
    html = html.replace("</body>", "  <script>\n" + js + "\n  </script>\n</body>", 1)

    # The Apps Script build must never ship demo-only or localhost assets.
    html = html.replace('href="./brand.svg"', 'href="data:image/svg+xml,'
                        + "%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 64 64'%3E"
                        + "%3Crect x='5' y='7' width='54' height='53' rx='18' fill='%23e3f2ec'/%3E"
                        + "%3Cpath d='M21 5v12M43 5v12' stroke='%23167d72' stroke-width='4' stroke-linecap='round'/%3E"
                        + "%3Crect x='13' y='15' width='38' height='36' rx='10' fill='%23fff' stroke='%23167d72' stroke-width='3'/%3E"
                        + "%3Cpath d='M19 34h8l4-8 6 17 4-9h6' fill='none' stroke='%23167d72' stroke-width='3' stroke-linecap='round' stroke-linejoin='round'/%3E%3C/svg%3E")
    html = re.sub(r'\n[ \t]*<link rel="preload"[^>]*>', "", html)
    # Favicons with inline SVG data URIs do not render reliably in Safari; drop them in the GAS bundle.
    html = re.sub(r'\n[ \t]*<link rel="(icon|manifest)"[^>]*>', "", html)
    html = re.sub(r'\n[ \t]*<script type="application/ld\+json">.*?</script>', "", html, flags=re.S)

    # HtmlService renders inside a sandboxed iframe: keep links inside it.
    html = html.replace("</title>", "</title>\n  <base target=\"_top\">", 1)

    # The published privacy notice lives in its own file (privacy.html) and is not part of the
    # Apps Script bundle. Inside HtmlService that link would open a 404, so it is re-pointed at
    # the bottom "الخصوصية وحقوق البيانات" section, which is the same text embedded above.
    html = re.sub(r'href="\./privacy\.html"', 'href="#privacyNotice"', html)

    (OUT / "Index.html").write_text(html, encoding="utf-8")

    for name in COPIED_FILES:
        source = ROOT / name
        if source.exists():
            (OUT / name).write_text(source.read_text(encoding="utf-8"), encoding="utf-8")

    print(f"Built {OUT.relative_to(ROOT)}/ ({(OUT / 'Index.html').stat().st_size:,} bytes Index.html, "
          f"{(OUT / 'Fonts.html').stat().st_size:,} bytes Fonts.html)")


if __name__ == "__main__":
    main()
